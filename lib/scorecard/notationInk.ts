export function notationInk(notation: string, bounds = { centerX: 50, top: 21, width: 76, height: 10 }): Stroke[] {
  const text = notation.trim().toUpperCase()
  if (!text) return []
  const width = text.length * 8 - 2
  const scale = Math.min(bounds.width / (width + 1), bounds.height / 10)
  const left = bounds.centerX - width * scale / 2
  return [...text].flatMap((letter, i) => (GLYPHS[letter] || []).map(stroke => stroke.map(([x, y]) => [
    left + (i * 8 + x + (10 - y) * 0.07) * scale,
    bounds.top + y * scale,
  ] as [number, number])))
}
